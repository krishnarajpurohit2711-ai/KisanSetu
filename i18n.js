function localizedValue(group, value) {
  const current = localizedValues[getLanguage()] || localizedValues.en;
  const fallback = localizedValues.en;
  return current[group]?.[value]
    || fallback[group]?.[value]
    || Object.values(current).find((values) => values?.[value])?.[value]
    || Object.values(fallback).find((values) => values?.[value])?.[value]
    || value;
}

function formatLocalizedNumber(value, options = {}) {
  const locale = getLanguage() === 'en' ? 'en-IN' : `${getLanguage()}-IN-u-nu-deva`;
  return new Intl.NumberFormat(locale, options).format(Number(value));
}

function formatLocalizedCurrency(value) {
  return `₹ ${formatLocalizedNumber(value)}`;
}

function localizeDigits(value) {
  return String(value).replace(/\d+(?:[.,]\d+)?/g, (match) => formatLocalizedNumber(match.replace(/,/g, '')));
}

function formatLocalizedUnit(value, unit) {
  return `${formatLocalizedNumber(value, { maximumFractionDigits: 2 })} ${localizedValue('units', unit)}`;
}

function t(path) {
  const lang = getLanguage();
  const fallback = appTranslations.en;
  const segments = path.split('.');

  let value = appTranslations[lang] || fallback;
  for (const segment of segments) {
    value = value && value[segment];
    if (value === undefined || value === null) {
      value = fallback;
      for (const fallbackSegment of segments) {
        value = value && value[fallbackSegment];
        if (value !== undefined && value !== null) break;
      }
      return value || path;
    }
  }
  return value || path;
}

function setLanguage(lang) {
  localStorage.setItem('kisansetu_lang', lang);
  document.documentElement.lang = lang;
  applyTranslations();
  document.dispatchEvent(new CustomEvent('kisansetu:languagechange', { detail: { lang } }));
}

function applyTranslations() {
  const lang = getLanguage();
  document.documentElement.lang = lang;
  const pageTitleKey = window.location.pathname.endsWith('login.html')
    ? 'loginTitle'
    : window.location.pathname.endsWith('farmer-dashboard.html')
      ? 'farmerTitle'
      : window.location.pathname.endsWith('buyer-dashboard.html')
        ? 'buyerTitle'
        : window.location.pathname.endsWith('admin-dashboard.html')
          ? 'adminTitle'
          : 'landingTitle';
  document.title = localizedValue('misc', pageTitleKey);
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = t(element.dataset.i18n);
    if (typeof value === 'string' && value) {
      element.textContent = getLanguage() === 'en' ? value : localizeDigits(value);
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const value = t(element.dataset.i18nHtml);
    if (typeof value === 'string' && value) {
      element.innerHTML = getLanguage() === 'en' ? value : localizeDigits(value);
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
  });

  document.querySelectorAll('.language-switch').forEach((select) => {
    select.value = lang;
  });

  document.querySelectorAll('[data-localize-group][data-localize-key]').forEach((element) => {
    element.textContent = localizedValue(element.dataset.localizeGroup, element.dataset.localizeKey);
  });

  document.querySelectorAll('[data-localize-number]').forEach((element) => {
    element.textContent = formatLocalizedNumber(element.dataset.localizeNumber, {
      maximumFractionDigits: Number(element.dataset.maximumFractionDigits || 2),
    });
  });
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.language-switch').forEach((select) => {
    select.addEventListener('change', (event) => {
      setLanguage(event.target.value);
    });
  });
  applyTranslations();
});
